"""Print convolution shapes, attributes, weights, and MAC estimates from ONNX."""

from pathlib import Path

import onnx
from onnx import helper, shape_inference

OUTPUT_DIR = Path(__file__).resolve().parent / "outputs"
MODEL_NAMES = ("baseline", "narrow")
CONVOLUTION = "Conv"


def inspect_model(model_path):
    """Infer shapes and summarize every convolution in one exported model."""
    model = shape_inference.infer_shapes(onnx.load(str(model_path)))
    shapes = {}
    for value in (
        list(model.graph.input) + list(model.graph.value_info) + list(model.graph.output)
    ):
        shape = value.type.tensor_type.shape.dim
        shapes[value.name] = [dimension.dim_value or "?" for dimension in shape]
    weights = {initializer.name: list(initializer.dims) for initializer in model.graph.initializer}
    print(f"\n{model_path.name}")
    for node in model.graph.node:
        if node.op_type != CONVOLUTION:
            continue
        attributes = {
            attribute.name: helper.get_attribute_value(attribute)
            for attribute in node.attribute
        }
        weight_shape = weights.get(node.input[1], "?")
        input_shape = shapes.get(node.input[0], "?")
        output_shape = shapes.get(node.output[0], "?")
        print(
            f"Conv input={input_shape}, output={output_shape}, "
            f"weights={weight_shape}, groups={attributes.get('group', 1)}"
        )


def main():
    """Inspect the baseline and narrow ONNX graphs generated by the lab."""
    for model_name in MODEL_NAMES:
        model_path = OUTPUT_DIR / f"{model_name}.onnx"
        if not model_path.exists():
            raise FileNotFoundError(f"Export both models first; missing {model_path}")
        inspect_model(model_path)


if __name__ == "__main__":
    main()
